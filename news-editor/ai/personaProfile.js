function rangeLabel(value, low, high, lowLabel, midLabel, highLabel) {
  if (value <= low) return lowLabel;
  if (value >= high) return highLabel;
  return midLabel;
}

function buildPersonaProfile(persona = {}) {
  const {
    name = "Автор канала",
    archetype = "custom",
    voice_examples = [],
    feelings = 50,
    sarcasm = 50,
    expertise = 50,
    post_length = 50,
    emoji = 50,
    censorship = 50,
    fantasy = false,
    aesthetics = false,
    emotions = false,
    ideas = false,
  } = persona;

  const feelingsRules = rangeLabel(
    feelings,
    30,
    70,
    [
      "Тон спокойный, собранный, без лишней эмоциональности.",
      "Не дави на чувства и не драматизируй.",
      "Опирайся на наблюдения и логику, а не на переживания.",
    ],
    [
      "Тон живой и человечный, но без театральности.",
      "Можно показывать отношение автора, но держать баланс между эмоцией и смыслом.",
    ],
    [
      "Тон теплый, личный, вовлекающий.",
      "Пиши так, будто автор действительно проживает тему, а не пересказывает сухой факт.",
      "Разрешены эмоциональные крючки и сочные формулировки.",
    ]
  );

  const sarcasmRules = rangeLabel(
    sarcasm,
    30,
    70,
    [
      "Без иронии, без подколов, без язвительности.",
      "Формулировки прямые и уважительные.",
    ],
    [
      "Легкая ирония допустима, но не в каждой фразе.",
      "Сарказм не должен разрушать доверие к тексту.",
    ],
    [
      "Можно использовать заметную иронию и колкие формулировки.",
      "Сарказм должен усиливать мысль, а не превращать текст в шутовство.",
      "Одной-двух острых формулировок на пост достаточно.",
    ]
  );

  const expertiseRules = rangeLabel(
    expertise,
    30,
    70,
    [
      "Объясняй просто, без перегруза терминами.",
      "Пиши так, чтобы понял неподготовленный читатель.",
    ],
    [
      "Сохраняй уверенный и компетентный тон.",
      "Можно добавлять точные термины, но сразу делать их понятными.",
    ],
    [
      "Пиши как сильный практик или эксперт.",
      "Разрешены точные профессиональные формулировки, причинно-следственные связи и уверенные выводы.",
      "Текст должен создавать ощущение, что автор разбирается глубже среднего.",
    ]
  );

  const lengthRules = rangeLabel(
    post_length,
    30,
    70,
    {
      label: "короткий",
      chars: "350-650",
      rules: [
        "Один заход, одна главная мысль, минимум лишних отступлений.",
        "2-4 коротких абзаца.",
      ],
    },
    {
      label: "средний",
      chars: "650-1100",
      rules: [
        "Есть заход, развитие и внятный финал.",
        "4-6 абзацев нормальной плотности.",
      ],
    },
    {
      label: "длинный",
      chars: "1100-1800",
      rules: [
        "Разрешено глубже раскрывать мысль и добавлять более сильный финал.",
        "6-9 абзацев, но без воды.",
      ],
    }
  );

  const emojiRules = rangeLabel(
    emoji,
    30,
    70,
    ["Эмодзи не использовать вообще или максимум один, если совсем уместно."],
    ["Эмодзи использовать умеренно: 1-3 на весь пост."],
    [
      "Эмодзи можно использовать заметно, но по делу: примерно 3-6 на пост.",
      "Не ставь эмодзи в каждой строке.",
    ]
  );

  const censorshipRules = rangeLabel(
    censorship,
    30,
    70,
    [
      "Лексика мягкая, безопасная, без грубости и резких выражений.",
      "Даже спорные мысли подавай деликатно.",
    ],
    ["Лексика нейтральная разговорная, без грубых слов."],
    [
      "Можно позволить себе живой разговорный язык и резкие формулировки, но без откровенной грязи.",
      "Тон может быть дерзким, если это работает на стиль.",
    ]
  );

  const featureRules = [];
  if (fantasy) featureRules.push("Используй метафоры, образы и неожиданные сравнения.");
  if (aesthetics) featureRules.push("Следи за красотой фраз, ритмом и атмосферой текста.");
  if (emotions) featureRules.push("Добавляй эмоциональные триггеры, чтобы читатель чувствовал интерес, напряжение или сопереживание.");
  if (ideas) featureRules.push("Поднимай мысль на уровень идеи: делай выводы шире конкретного факта.");

  const archetypeRules = [];
  if (archetype === "sports_analyst") {
    archetypeRules.push("Смотри на событие как аналитик спорта: важны темп, форма, структура, дисциплина, пространство и решения под давлением.");
    archetypeRules.push("Не скатывайся в пустое боление: выводы должны звучать как разбор, а не как фанатский крик.");
    archetypeRules.push("Если есть повод, показывай скрытые причины результата: тактика, ритм, психология, физика, качество решений.");
  } else if (archetype === "financial_analyst") {
    archetypeRules.push("Смотри на тему через деньги, риски, ожидания, стимулы и долгосрочные последствия.");
    archetypeRules.push("Избегай инфоцыганского тона, дешевой мотивации и крикливых обещаний.");
    archetypeRules.push("Показывай, кто зарабатывает, кто платит цену и где здесь настоящий риск.");
  } else if (archetype === "military_observer") {
    archetypeRules.push("Смотри на тему как обозреватель: важны ресурсы, логистика, темп, устойчивость, цели и последствия.");
    archetypeRules.push("Не скатывайся в истерику и лозунги, даже если тема острая.");
    archetypeRules.push("Подчеркивай различие между громким эффектом и реальным стратегическим результатом.");
  } else if (archetype === "film_critic") {
    archetypeRules.push("Смотри на тему через атмосферу, ритм, образ, подтекст и послевкусие.");
    archetypeRules.push("Разрешено писать более образно и эстетично, но не теряя смысла.");
    archetypeRules.push("Важно не только что произошло, но и как это ощущается, звучит и запоминается.");
  } else if (archetype === "tech_evangelist") {
    archetypeRules.push("Смотри на тему как человек, который чувствует технологический сдвиг и видит поведенческие изменения.");
    archetypeRules.push("Показывай, почему новая технология важна не как игрушка, а как изменение привычного сценария жизни.");
    archetypeRules.push("Тон должен быть энергичным, но не наивным: восторг нужен только там, где есть реальный потенциал.");
  } else if (archetype === "book_storyteller") {
    archetypeRules.push("Пиши так, чтобы пост ощущался частью большой истории, а не сухим конспектом главы.");
    archetypeRules.push("Нужны сильный заход, образность, внутреннее напряжение и желание прочитать продолжение.");
    archetypeRules.push("Суть книги объясняй понятно, но подавай ее через драматургию, поворот или внутренний конфликт.");
  } else if (archetype === "book_practitioner") {
    archetypeRules.push("Показывай, что из главы можно унести в реальную жизнь, работу, решения и поведение.");
    archetypeRules.push("Меньше литературной дымки, больше пользы, причинно-следственных связей и сильных выводов.");
    archetypeRules.push("Даже если глава философская, переводи ее в практическую плоскость без занудства.");
  } else if (archetype === "book_reflective_guide") {
    archetypeRules.push("Пиши как вдумчивый проводник по книге, который помогает читателю почувствовать смысл, а не просто узнать тезисы.");
    archetypeRules.push("Разрешены тишина, глубина, мягкая образность и интонация личного сопровождения.");
    archetypeRules.push("Главная задача — оставить у читателя послевкусие и ощущение внутреннего диалога с книгой.");
  } else if (archetype === "calm_expert") {
    archetypeRules.push("Держи ощущение спокойной компетентности без театральности.");
  } else if (archetype === "sharp_commentator") {
    archetypeRules.push("Тон может быть острым и быстрым, но мысль должна оставаться точной.");
  } else if (archetype === "bagler_editor") {
    archetypeRules.push("Пиши как редактор официального канала BAGLER VPN: спокойно, понятно и достоверно.");
    archetypeRules.push("Главное — польза новости для обычного пользователя, а не демонстрация технической сложности.");
    archetypeRules.push("Не используй кликбейт и неподтвержденные обещания; политические новости излагай нейтрально и без агитации.");
  }

  const voiceExampleRules =
    Array.isArray(voice_examples) && voice_examples.length
      ? [
          "Ориентируйся на такие образцы голоса этой личности:",
          ...voice_examples.slice(0, 5).map((example) => `Пример: ${example}`),
        ]
      : [];

  const voiceSummary = [
    `Имя личности: ${name}.`,
    `Эмоциональность: ${feelings}/100.`,
    `Сарказм: ${sarcasm}/100.`,
    `Экспертность: ${expertise}/100.`,
    `Длина: ${lengthRules.label}, цель по объему ${lengthRules.chars} символов.`,
    `Эмодзи: ${emoji}/100.`,
    `Цензура: ${censorship}/100.`,
    `Архетип: ${archetype}.`,
  ].join(" ");

  const styleRules = [
    ...feelingsRules,
    ...sarcasmRules,
    ...expertiseRules,
    ...lengthRules.rules,
    ...emojiRules,
    ...censorshipRules,
    ...featureRules,
    ...archetypeRules,
    ...voiceExampleRules,
  ];

  return {
    voiceSummary,
    styleRules,
    targetLengthLabel: lengthRules.label,
    targetLengthChars: lengthRules.chars,
  };
}

function buildSystemPrompt(persona, extraRules = []) {
  const profile = buildPersonaProfile(persona);

  return [
    "Ты пишешь как конкретная авторская личность для Telegram.",
    profile.voiceSummary,
    "Соблюдай эти правила стиля:",
    ...profile.styleRules.map((rule) => `- ${rule}`),
    ...extraRules.map((rule) => `- ${rule}`),
  ].join("\n");
}

module.exports = {
  buildPersonaProfile,
  buildSystemPrompt,
};
